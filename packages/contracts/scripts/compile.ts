/**
 * Compiles contracts/P2PMarket.sol and writes its ABI and creation bytecode to
 * src/p2p-market.artifact.ts, which is committed and reviewed like code.
 *
 *   npm run compile -w @pedospe/contracts
 *
 * Deployments are checked against this bytecode, so a changed contract is a
 * new artifact and a new deployment; `test/artifact.test.ts` recompiles the
 * source with the recorded settings and fails if the two disagree. Never edit
 * the artifact by hand.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const solc = createRequire(import.meta.url)('solc') as {
  version(): string;
  compile(input: string): string;
};

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const NAME = 'P2PMarket';

/**
 * `paris` (no PUSH0, no MCOPY) so the same bytecode deploys on every EVM
 * network, including test networks whose EVM version lags mainnet's. No
 * metadata hash, so comments and paths never change the bytecode.
 */
export const SETTINGS = {
  optimizer: { enabled: true, runs: 200 },
  evmVersion: 'paris',
  metadata: { bytecodeHash: 'none' },
  outputSelection: { '*': { [NAME]: ['abi', 'evm.bytecode.object'] } },
} as const;

const source = readFileSync(join(ROOT, 'contracts', `${NAME}.sol`), 'utf8');
const output = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: 'Solidity',
      sources: { [`${NAME}.sol`]: { content: source } },
      settings: SETTINGS,
    }),
  ),
) as {
  errors?: { severity: string; formattedMessage: string }[];
  contracts: Record<string, Record<string, { abi: unknown[]; evm: { bytecode: { object: string } } }>>;
};
const errors = (output.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length > 0) throw new Error(errors.map((e) => e.formattedMessage).join('\n'));

const compiled = output.contracts[`${NAME}.sol`][NAME];
const sourceSha256 = createHash('sha256').update(source).digest('hex');

writeFileSync(
  join(ROOT, 'src', 'p2p-market.artifact.ts'),
  `/**
 * GENERATED by \`npm run compile\` from contracts/${NAME}.sol.
 * Do not edit: deployments are checked against this bytecode.
 */
export const P2P_MARKET_ARTIFACT = {
  contractName: '${NAME}',
  compiler: '${solc.version()}',
  settings: ${JSON.stringify(SETTINGS)},
  sourceSha256: '${sourceSha256}',
  abi: ${JSON.stringify(compiled.abi)},
  bytecode: '0x${compiled.evm.bytecode.object}',
} as const;
`,
);
console.log(`${NAME} compiled (${compiled.evm.bytecode.object.length / 2} bytes)`);
