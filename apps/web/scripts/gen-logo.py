# Builds the logo's outlines from the app's own Archivo file at the hero's cut (wdth 116, wght
# 720) and writes them to src/components/ui/logo-paths.ts:
#
# - MARK: the capital M cut on a slant (the cut 28 units wide, rising 190 units over 1500), its
#   lower part slid 52 units right.
# - WORDMARK: MID at full size and POINT at 50 %, each letter cut the same way, POINT's O whole
#   with a dot at its centre.
#
# Paths are in font units (1000 per em, baseline at 0, y pointing down), as finished outlines
# (boolean operations, no clip paths), so the favicon and the icons draw them too. Run it after
# changing the design, then `npm run icons -w @midpoint/web`:
#
#   python -m pip install --user fonttools brotli skia-pathops
#   python apps/web/scripts/gen-logo.py
import json
import math
import os

import pathops
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.dirname(HERE)
FONT = os.path.join(
    WEB, '..', '..', 'node_modules', '@fontsource-variable', 'archivo', 'files',
    'archivo-latin-wdth-normal.woff2',
)
OUT = os.path.join(WEB, 'src', 'components', 'ui', 'logo-paths.ts')

CAP = 687
TRACK = -12  # the hero's letter-spacing, -0.012em
SLOPE = -190 / 1500  # the cut rises to the right (y down per unit of x)
CUT_AT = 0.467  # the cut's height at a letter's centre, as a share of its cap height
GAP = 28
SLIDE = 52
POINT_SCALE = 0.5
DOT = 0.105  # the O's dot radius, as a share of the cap height

font = instantiateVariableFont(TTFont(FONT), {'wdth': 116, 'wght': 720})
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()


def glyph(ch, scale, dx):
    p = pathops.Path()
    g = glyphs[cmap[ord(ch)]]
    g.draw(TransformPen(p.getPen(), (scale, 0, 0, -scale, dx, 0)))
    return p, g.width * scale


def polygon(points):
    p = pathops.Path()
    pen = p.getPen()
    pen.moveTo(points[0])
    for pt in points[1:]:
        pen.lineTo(pt)
    pen.closePath()
    return p


def moved(p, dx):
    q = pathops.Path()
    p.draw(TransformPen(q.getPen(), (1, 0, 0, 1, dx, 0)))
    return q


def cut(p, scale):
    """The letter cut on the slant through its centre; the part below slides right."""
    x0, _, x1, _ = p.bounds
    xc, yc, half = (x0 + x1) / 2, -CAP * scale * CUT_AT, GAP * scale / 2
    left, right = x0 - 400, x1 + 400
    line = lambda x, off: yc + SLOPE * (x - xc) + off
    top = polygon([(left, -2000), (right, -2000), (right, line(right, -half)), (left, line(left, -half))])
    bottom = polygon([(left, line(left, half)), (right, line(right, half)), (right, 2000), (left, 2000)])
    upper = pathops.op(p, top, pathops.PathOp.INTERSECTION)
    lower = pathops.op(p, bottom, pathops.PathOp.INTERSECTION)
    return pathops.op(upper, moved(lower, SLIDE * scale), pathops.PathOp.UNION)


def dot(p, scale):
    """The O with a dot at its centre."""
    x0, y0, x1, y1 = p.bounds
    cx, cy, r = (x0 + x1) / 2, (y0 + y1) / 2, DOT * CAP * scale
    circle = polygon([(cx + r * math.cos(2 * math.pi * i / 64), cy + r * math.sin(2 * math.pi * i / 64)) for i in range(64)])
    return pathops.op(p, circle, pathops.PathOp.UNION)


def word(parts):
    total, x = pathops.Path(), 0.0
    for text, scale in parts:
        for ch in text:
            p, advance = glyph(ch, scale, x)
            p = dot(p, scale) if ch == 'O' else cut(p, scale)
            total = pathops.op(total, p, pathops.PathOp.UNION)
            x += advance + TRACK * scale
    return total


def entry(p):
    pen = SVGPathPen(None, ntos=lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
    p.draw(pen)
    x0, y0, x1, y1 = p.bounds
    # The box keeps the cap line and the baseline, so marks of different letters line up.
    top, bottom = min(y0, -CAP), max(y1, 0)
    box = [round(x0, 1), round(top, 1), round(x1 - x0, 1), round(bottom - top, 1)]
    return {'d': pen.getCommands(), 'box': box}


logo = {'mark': entry(word([('M', 1.0)])), 'wordmark': entry(word([('MID', 1.0), ('POINT', POINT_SCALE)]))}
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write(
        '/* Generated by scripts/gen-logo.py from the app\'s Archivo file (wdth 116, wght 720): do not\n'
        '   edit by hand. Paths in font units (1000 per em, baseline at 0, y pointing down); box = x,\n'
        '   y, width, height. scripts/gen-icons.mjs reads this file too. */\n'
        f'export const LOGO = {json.dumps(logo, separators=(",", ":"))} as const;\n'
    )
print('wrote', os.path.relpath(OUT, WEB), {k: (len(v['d']), v['box']) for k, v in logo.items()})
