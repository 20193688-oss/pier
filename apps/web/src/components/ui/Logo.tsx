/* The product's logo: PIER drawn from the hero's letters (Archivo at the hero's cut: width
   116, weight 720), every letter cut on a slant with its lower part slid right. LogoGlyph is the
   cut P alone. Both are flat, in the current colour, on no tile; only the app icons and the
   favicon set the P on an ink tile
   (scripts/gen-icons.mjs). The outlines live in logo-paths.ts, generated by scripts/gen-logo.py
   from the app's own font file; they spell the name, so a new name means running it again. */
import { LOGO } from '@/components/ui/logo-paths';
import { BRAND } from '@/lib/brand';

const widthFor = (box: readonly number[], height: number) => Math.round((height * box[2]) / box[3]);

/** The cut P alone, in the current colour; `size` is its height in px. */
export function LogoGlyph({ size = 120, className = '' }: { size?: number; className?: string }) {
  return (
    <svg
      width={widthFor(LOGO.mark.box, size)}
      height={size}
      viewBox={LOGO.mark.box.join(' ')}
      className={className}
      aria-hidden="true"
      focusable="false"
      fill="currentColor"
    >
      <path d={LOGO.mark.d} />
    </svg>
  );
}

/** The wordmark in the current colour (the page's ink by default); `size` is its height in px.
    Assistive tech reads `label`, else the product's name. */
export function Logo({
  size = 22,
  label,
  className = 'block text-ink',
}: {
  size?: number;
  label?: string;
  className?: string;
}) {
  return (
    <svg
      width={widthFor(LOGO.wordmark.box, size)}
      height={size}
      viewBox={LOGO.wordmark.box.join(' ')}
      className={className}
      role="img"
      aria-label={label ?? BRAND.name}
      focusable="false"
      fill="currentColor"
    >
      <path d={LOGO.wordmark.d} />
    </svg>
  );
}
